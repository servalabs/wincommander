export type IconName = keyof typeof ICON_MAP | (string & {});

type Intent = "success" | "warning" | "danger" | "primary" | "none" | string;

export interface IconProps extends Omit<LucideProps, "ref"> {
  icon: IconName;
  /** Pixel size; maps to lucide's numeric `size`. */
  size?: number;
  /** Tooltip/native title (Blueprint Icon accepted this). */
  title?: string;
  /** Blueprint-compatibility prop; mapped to a CSS color var. */
  intent?: Intent;
  /** Explicit color; takes precedence when no intent is given. */
  color?: string;
}

const INTENT_COLOR: Record<string, string> = {
  success: "var(--ok)",
  warning: "var(--warn)",
  danger: "var(--danger)",
  primary: "var(--accent)",
  none: "currentColor",
};

export function Icon({ icon, size = 16, intent, color, ...props }: IconProps) {
  const Cmp = ICON_MAP[icon] ?? Circle;
  const resolvedColor =
    intent != null ? (INTENT_COLOR[intent] ?? color) : color;
  // `intent` is destructured out above so it is never forwarded onto the
  // underlying SVG as an unknown DOM attribute.
  return <Cmp size={size} color={resolvedColor} {...props} />;
}

export default Icon;
