//
// WinCommander V2 migrates off @blueprintjs/core. Blueprint exposed a single
// <Icon icon="kebab-name" /> component backed by its own icon set; lucide-react
// uses PascalCase named component exports. This shim keeps the existing call
// sites unchanged — `<Icon icon="warning-sign" size={16} className=... />` —
// by translating each Blueprint icon-name string used anywhere in src/ to the
// closest real lucide-react icon component.
//
// To add a new Blueprint name: import a VERIFIED lucide export (confirm it
// exists in node_modules/lucide-react/dist/lucide-react.d.ts — a wrong name
// breaks the build) and add a "blueprint-name": Component entry to ICON_MAP.
// Every imported icon must appear in the map (noUnusedLocals is on). Unknown
// names fall back to Circle at runtime.

