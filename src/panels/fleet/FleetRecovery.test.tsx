import { expect, test } from "bun:test";

declare const Bun: {
  which(name: string): string | null;
  spawn(args: string[], options: { stdout: "pipe"; stderr: "pipe" }): { stderr: ReadableStream<Uint8Array>; exited: Promise<number> };
};

test("recovery receipt is validated and its service key is displayed as a fingerprint", async () => {
  const script = String.raw`
    import { mock } from 'bun:test';
    import { strict as assert } from 'node:assert';
    import { JSDOM } from 'jsdom';
    const dom = new JSDOM('<div id="root"></div>', { url:'http://localhost' });
    globalThis.window=dom.window; globalThis.document=dom.window.document; globalThis.navigator=dom.window.navigator;
    globalThis.IS_REACT_ACT_ENVIRONMENT=true;
    const React=await import('react'); const { act,createElement:h }=React;
    const { createRoot }=await import('react-dom/client');
    const calls=[]; let conflict=false;
    mock.module('@tauri-apps/api/core',()=>({invoke:async (name,args)=>{ calls.push([name,args]);
      if(name==='fleet_recovery_stage') return {candidate_public_key:btoa(String.fromCharCode(...new Uint8Array(32))),submission_conflict:conflict};
      if(name==='fleet_recovery_handoff') return {recovery_id:'fixture'};
      if(name==='fleet_recovery_pin_operator_key') return {pinned:true};
      if(name==='fleet_recovery_resume') return {status:'restart_required'};
      return {status:'credential_committed_pending_approval'}; }}));
    mock.module('@/components/ui/button',()=>({Button:({children,variant,...props})=>h('button',props,children)}));
    const {default:View}=await import('./src/panels/fleet/FleetRecovery');
    const host=document.getElementById('root'), root=createRoot(host);
    await act(async()=>root.render(h(View)));
    assert.match(host.textContent,/Fleet record remains retired/);
    assert.match(host.textContent,/does not reconnect it to Fleet/);
    const [operator,textarea]=host.querySelectorAll('textarea');
    const button=name=>[...host.querySelectorAll('button')].find(element=>element.textContent===name);
    const input=Object.getOwnPropertyDescriptor(dom.window.HTMLTextAreaElement.prototype,'value').set;
    const enter=async value=>act(async()=>{input.call(textarea,value); textarea.dispatchEvent(new dom.window.Event('input',{bubbles:true}));});
    await enter('not json');
    await act(async()=>button('Prepare identity').click());
    assert.match(host.textContent,/complete signed receipt/); assert.equal(calls.length,0);
    await enter('{"retirement_id":"fixture"}');
    await act(async()=>{button('Prepare identity').click(); await new Promise(r=>setTimeout(r,10));});
    assert.equal(calls[0][0],'fleet_recovery_stage'); assert.deepEqual(calls[0][1],{retirementReceipt:{retirement_id:'fixture'}});
    assert.match(host.textContent,/66687aadf862bd776c8fc18b8e9f8e20089714856ee233b3902a591d0d5f2925/);
    assert.match(host.textContent,/proposal was sent/);
    assert.match(host.textContent,/check that it appears/);
    assert.match(host.textContent,/does not confirm a connection/);
    assert.equal(button('Finish recovery').disabled,true);
    await act(async()=>button('Check approved handoff').click());
    await act(async()=>button('Finish recovery').click());
    assert.deepEqual(calls[2],['fleet_recovery_finish',{retirementReceipt:{retirement_id:'fixture'},handoff:{recovery_id:'fixture'}}]);
    assert.match(host.textContent,/Approve this device in Fleet/);
    await act(async()=>button('Resume prepared recovery').click());
    assert.match(host.textContent,/Restart Windows/);
    assert.match(host.textContent,/fresh retirement receipt/);
    assert.match(host.textContent,/Finish recovery again/);
    assert.match(host.textContent,/not yet reconnected/);
    conflict=true;
    await act(async()=>{button('Prepare identity').click(); await new Promise(r=>setTimeout(r,10));});
    assert.match(host.textContent,/Fleet reported a conflict/);
    assert.match(host.textContent,/Do not approve if they differ/);
    assert.match(host.textContent,/66687aadf862bd776c8fc18b8e9f8e20089714856ee233b3902a591d0d5f2925/);
    await act(async()=>{input.call(operator,btoa(String.fromCharCode(...new Uint8Array(32))));operator.dispatchEvent(new dom.window.Event('input',{bubbles:true}));});
    await act(async()=>button('Review operator key').click());
    assert.match(host.textContent,/Operator key fingerprint/);
    assert.equal(button('Save operator key').disabled,true);
    await act(async()=>host.querySelector('input[type="checkbox"]').click());
    await act(async()=>{input.call(operator,btoa(String.fromCharCode(...new Uint8Array(32).fill(1))));operator.dispatchEvent(new dom.window.Event('input',{bubbles:true}));});
    assert.equal(button('Save operator key'),undefined);
    await act(async()=>button('Review operator key').click());
    assert.equal(button('Save operator key').disabled,true);
    await act(async()=>host.querySelector('input[type="checkbox"]').click());
    await act(async()=>button('Save operator key').click());
    assert.deepEqual(calls.at(-1),['fleet_recovery_pin_operator_key',{operatorKey:btoa(String.fromCharCode(...new Uint8Array(32).fill(1)))}]);
    await act(async()=>root.unmount());
  `;
  const proc = Bun.spawn([Bun.which("bun")!, "--eval", script], { stdout: "pipe", stderr: "pipe" });
  const stderr = await new Response(proc.stderr).text();
  expect({ exit: await proc.exited, stderr }).toEqual({ exit: 0, stderr: "" });
}, 30_000);
