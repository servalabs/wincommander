//! WinCommander SYSTEM service (`wincommander-svc.exe`)
//!
//! # Modes
//!
//! * `--console`  — dev / debugging mode: runs a tokio multi-thread runtime
//!   directly without registering with the SCM.  Useful with `cargo run`.
//!
//! * *(no flag)*  — production mode: on Windows, hands control to the SCM
//!   dispatcher via `windows-service`; on non-Windows, prints a note and exits.
//!
//! # Phase 0 scope
//!
//! The four background loops are **stubbed** (30-second sleep bodies with doc
//! comments).  Phase 2 wires the enforcement loop; Phase 3 wires reconciler,
//! command-worker, and fleet-conn.

// ── Non-Windows stub ─────────────────────────────────────────────────────────
// On Linux CI we only need `cargo check` / `cargo build` to succeed.
// No pipe, no SCM, no windows-sys.

#[cfg(not(windows))]
fn main() {
    println!("WinCommander service: endpoint enforcement is Windows-only (build-only stub)");
    std::process::exit(0);
}

