"""Reproduce the compiled-in, pinned Gitleaks content rules; no network I/O."""
import hashlib
import json
import re
from pathlib import Path
import sys
import tomllib

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "gitleaks-v8.24.3.toml"
EXPECTED = "8f393899dbdc67e4eae580909e496acab9cf3a75aacfb6fac56b6eb16bb9e051"
TARGET = HERE.parents[1] / "src-tauri/wincmd-clip-rules/src/secret_rules.rs"

def rust_regex(pattern):
    return re.sub(r"(?<!\\)\{(?![0-9]+(?:,[0-9]*)?\})", r"\\{", pattern)

def literal(value):
    if isinstance(value, str):
        return 'r####"' + value + '"####'
    return "&[" + ",".join(literal(v) for v in value) + "]"

def generate():
    data = SOURCE.read_bytes()
    if hashlib.sha256(data).hexdigest() != EXPECTED:
        raise SystemExit("Pinned rule input hash mismatch")
    config = tomllib.loads(data.decode())
    lines = ["// SPDX-License-Identifier: AGPL-3.0-or-later", "// Generated by tools/import-secret-rules/import.py; Gitleaks v8.24.3 (MIT).", "use super::{SecretAllowlist, SecretRule};", "#[rustfmt::skip]", "pub(crate) static SECRET_RULES: &[SecretRule] = &["]
    skipped = []
    for rule in config["rules"]:
        if not rule.get("regex"):
            skipped.append(rule["id"])
            continue
        # File path conditions cannot apply to clipboard content. Rules requiring
        # a path are disabled by default, while their text pattern remains testable.
        allowlists = []
        for allow in rule.get("allowlists", []):
            if allow.get("condition") == "AND" and allow.get("paths"):
                continue
            allowlists.append("SecretAllowlist { target:" + literal(allow.get("regexTarget", "secret")) + ",regexes:" + literal([rust_regex(p) for p in allow.get("regexes", [])]) + ",stopwords:" + literal(allow.get("stopwords", [])) + " }")
        values = [literal(rule["id"]), literal(rust_regex(rule["regex"])), literal(rule.get("keywords", [])), str(float(rule.get("entropy", 0))), "&[" + ",".join(allowlists) + "]", str(not bool(rule.get("path"))).lower()]
        lines.append("SecretRule { id:%s, regex:%s, keywords:%s, entropy:%s, allowlists:%s, default_enabled:%s }," % tuple(values))
    lines += ["];", "#[rustfmt::skip]", "pub(crate) static GLOBAL_ALLOW_REGEXES: &[&str] = " + literal([rust_regex(p) for p in config["allowlist"].get("regexes", [])]) + ";", "#[rustfmt::skip]", "pub(crate) static GLOBAL_STOPWORDS: &[&str] = " + literal(config["allowlist"].get("stopwords", [])) + ";", ""]
    output = "\n".join(lines)
    if "--check" in sys.argv:
        if TARGET.read_text(encoding="utf-8") != output:
            raise SystemExit("Generated secret rule table has drifted")
    else:
        TARGET.write_text(output, encoding="utf-8", newline="\n")
    print(json.dumps({"rules": len(config["rules"]) - len(skipped), "unsupported_path_only_rules": skipped, "sha256": EXPECTED}))

if __name__ == "__main__":
    generate()
